function readInitialLocale(): AdminLocale {
  if (typeof window === 'undefined') return 'fr';
  const saved = window.localStorage.getItem(STORAGE_KEY);
  return saved === 'fr' || saved === 'en' || saved === 'he' ? saved : 'fr';
}

const locale = ref<AdminLocale>(readInitialLocale());

export function useAdminI18n() {
  const direction = computed<'ltr' | 'rtl'>(() => locale.value === 'he' ? 'rtl' : 'ltr');
  const isRtl = computed(() => direction.value === 'rtl');

  function setLocale(nextLocale: AdminLocale): void {
    locale.value = nextLocale;
    if (typeof window !== 'undefined') {
      window.localStorage.setItem(STORAGE_KEY, nextLocale);
    }
  }

  function t(key: string, params: TranslationParams = {}): string {
    const template = messages[locale.value][key] ?? messages.fr[key] ?? key;
    return Object.entries(params).reduce(
      (result, [name, value]) => result.replaceAll(`{${name}}`, String(value)),
      template
    );
  }

  return {
    locale,
    direction,
    isRtl,
    setLocale,
    t
  };
}
